function escapeRegExp(str) {
  return str.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// בדיקת QA best-effort: מזהירה (לא חוסמת) אם משפט התיאור מכיל את המילה
// עצמה כמילה שלמה — רלוונטי בעיקר למילים בודדות (לא ביטויים).
function containsWordItself(englishWord, description) {
  if (/\s/.test(englishWord.trim())) return false; // ביטוי רב-מילים — לא בודקים
  const cleanWord = englishWord.replace(/[^a-zA-Z]/g, '');
  if (!cleanWord) return false;
  const re = new RegExp(`\\b${escapeRegExp(cleanWord)}\\b`, 'i');
  return re.test(description);
}

// כמה מילים ברשימות מופיעות פעמיים עם משמעות שונה (למשל "bath" כשם עצם
